const LanguageContext = createContext<{
  language: Language; setLanguage: (language: Language) => void;
  t: (source: string, ...values: (string | number)[]) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return localStorage.getItem(storageKey) === 'en' ? 'en' : 'zh-CN'; }
    catch { return 'zh-CN'; }
  });
  const t = (source: string, ...values: (string | number)[]) =>
    (language === 'en' ? english[source] ?? source : source).replace(/\{(\d+)\}/g, (match, index) => String(values[Number(index)] ?? match));
  useEffect(() => {
    document.documentElement.lang = language;
    document.title = t('Parrotbook · 小小配音员');
    try { localStorage.setItem(storageKey, language); } catch { /* Still works when storage is unavailable. */ }
  }, [language]);
  return <LanguageContext value={{ language, setLanguage, t }}>{children}</LanguageContext>;
}

export function useLanguage() { return useContext(LanguageContext)!; }
